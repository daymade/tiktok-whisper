// ProviderComparison holds comparison results between embedding providers
type ProviderComparison struct {
	TargetText      string
	TranscriptionID int
	OpenAIAvailable bool
	GeminiAvailable bool
	OpenAIEmbedding []float32
	GeminiEmbedding []float32
	OpenAIGenerated bool
	GeminiGenerated bool
	CrossSimilarity float64 // Similarity between OpenAI and Gemini embeddings
	Dimensions      map[string]int
	GenerationTime  map[string]string
	Errors          map[string]string
}

// analyzeProviderEmbeddings retrieves or generates embeddings for comparison
func analyzeProviderEmbeddings(ctx context.Context, storage *vector.PgVectorStorage, apiKeys *config.APIKeys, id int, text string) (*ProviderComparison, error) {
	comparison := &ProviderComparison{
		TargetText:      text,
		TranscriptionID: id,
		OpenAIAvailable: apiKeys.OpenAI != "",
		GeminiAvailable: apiKeys.Gemini != "",
		Dimensions:      make(map[string]int),
		GenerationTime:  make(map[string]string),
		Errors:          make(map[string]string),
	}

	// Try to get existing embeddings if ID is provided
	if id > 0 {
		// Try OpenAI embedding
		if comparison.OpenAIAvailable {
			openaiEmbedding, err := storage.GetEmbedding(ctx, id, "openai")
			if err == nil {
				comparison.OpenAIEmbedding = openaiEmbedding
				comparison.Dimensions["openai"] = len(openaiEmbedding)
				comparison.GenerationTime["openai"] = "Retrieved from database"
			} else {
				comparison.Errors["openai"] = "Not found in database"
			}
		}

		// Try Gemini embedding
		if comparison.GeminiAvailable {
			geminiEmbedding, err := storage.GetEmbedding(ctx, id, "gemini")
			if err == nil {
				comparison.GeminiEmbedding = geminiEmbedding
				comparison.Dimensions["gemini"] = len(geminiEmbedding)
				comparison.GenerationTime["gemini"] = "Retrieved from database"
			} else {
				comparison.Errors["gemini"] = "Not found in database"
			}
		}
	}

	// Generate missing embeddings if APIs are available
	if comparison.OpenAIAvailable && comparison.OpenAIEmbedding == nil {
		fmt.Println("🔄 Generating OpenAI embedding...")
		start := time.Now()
		embedding, err := generateTextEmbedding(ctx, text, "openai", apiKeys)
		if err != nil {
			comparison.Errors["openai"] = fmt.Sprintf("Generation failed: %v", err)
		} else {
			comparison.OpenAIEmbedding = embedding
			comparison.OpenAIGenerated = true
			comparison.Dimensions["openai"] = len(embedding)
			comparison.GenerationTime["openai"] = fmt.Sprintf("Generated in %v", time.Since(start).Round(time.Millisecond))
		}
	}

	if comparison.GeminiAvailable && comparison.GeminiEmbedding == nil {
		fmt.Println("🔄 Generating Gemini embedding...")
		start := time.Now()
		embedding, err := generateTextEmbedding(ctx, text, "gemini", apiKeys)
		if err != nil {
			comparison.Errors["gemini"] = fmt.Sprintf("Generation failed: %v", err)
		} else {
			comparison.GeminiEmbedding = embedding
			comparison.GeminiGenerated = true
			comparison.Dimensions["gemini"] = len(embedding)
			comparison.GenerationTime["gemini"] = fmt.Sprintf("Generated in %v", time.Since(start).Round(time.Millisecond))
		}
	}

	// Calculate cross-provider similarity if both embeddings are available
	if comparison.OpenAIEmbedding != nil && comparison.GeminiEmbedding != nil {
		// Since OpenAI (1536D) and Gemini (768D) have different dimensions,
		// we can't directly compare them. We'll note this limitation.
		if len(comparison.OpenAIEmbedding) == len(comparison.GeminiEmbedding) {
			comparison.CrossSimilarity = cosineSimilarity(comparison.OpenAIEmbedding, comparison.GeminiEmbedding)
		} else {
			comparison.CrossSimilarity = -1 // Indicates different dimensions
		}
	}

	return comparison, nil
}

