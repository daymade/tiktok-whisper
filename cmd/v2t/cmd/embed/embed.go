func runEmbedGenerate(cmd *cobra.Command, args []string) {
	// Load and validate API keys for embedding operations (fail-fast)
	apiKeys, err := config.GetAPIKeys()
	if err != nil {
		log.Fatalf("❌ Failed to load API keys: %v", err)
	}

	// Show API key status for embedding operations
	config.ShowAPIKeyStatus(apiKeys)

	// Require at least one API key for embedding operations
	if err := config.RequireAPIKeys(apiKeys); err != nil {
		log.Fatalf("❌ %v", err)
	}

	// Initialize database
	db, err := pg.GetConnection()
	if err != nil {
		log.Fatalf("Failed to connect to database: %v", err)
	}
	defer db.Close()

	// Test database connection
	if err := db.Ping(); err != nil {
		log.Fatalf("Failed to ping database: %v", err)
	}

	// Create providers based on flag and available API keys
	providers := make(map[string]provider.EmbeddingProvider)

	if flagProvider == "openai" || flagProvider == "both" {
		if apiKeys.OpenAI != "" {
			providers["openai"] = provider.NewOpenAIProvider(apiKeys.OpenAI)
			fmt.Println("✅ Using OpenAI provider for embeddings")
		} else if flagProvider == "openai" {
			log.Fatalf("❌ OpenAI provider requested but OPENAI_API_KEY not available")
		}
	}

	if flagProvider == "gemini" || flagProvider == "both" {
		if apiKeys.Gemini != "" {
			providers["gemini"] = provider.NewGeminiProvider(apiKeys.Gemini)
			fmt.Println("✅ Using Gemini provider for embeddings")
		} else if flagProvider == "gemini" {
			log.Fatalf("❌ Gemini provider requested but GEMINI_API_KEY not available")
		}
	}

	if len(providers) == 0 {
		log.Fatalf("❌ No embedding providers available for the requested configuration")
	}

	// Create storage and orchestrator
	storage := vector.NewPgVectorStorage(db)
	defer storage.Close()

	logger := &SimpleLogger{}
	embedOrchestrator := orchestrator.NewEmbeddingOrchestrator(providers, storage, logger)

	// Create batch processor
	processor := orchestrator.NewBatchProcessor(embedOrchestrator, storage, logger)

	ctx := context.Background()

	if flagAll {
		fmt.Println("Generating embeddings for all transcriptions...")
		// Determine which providers to process based on what's configured
		var providerNames []string
		for providerName := range providers {
			providerNames = append(providerNames, providerName)
		}
		err = processor.ProcessAllTranscriptions(ctx, providerNames, flagBatchSize)
	} else if flagUser != "" {
		fmt.Printf("Generating embeddings for user: %s\n", flagUser)

		// Determine which providers to process based on what's configured
		var providerNames []string
		for providerName := range providers {
			providerNames = append(providerNames, providerName)
		}

		if len(providerNames) == 0 {
			log.Fatalf("❌ No providers available. Please check your API key configuration.")
		}

		fmt.Printf("📊 Using providers: %v\n", providerNames)

		// Get user statistics before processing
		userStats, err := storage.GetUserEmbeddingStats(ctx, flagUser)
		if err != nil {
			log.Printf("⚠️  Unable to get user statistics: %v", err)
		} else {
			fmt.Printf("📈 User Statistics - Total: %d, OpenAI: %d, Gemini: %d, Pending OpenAI: %d, Pending Gemini: %d\n",
				userStats.TotalTranscriptions, userStats.OpenAIEmbeddings, userStats.GeminiEmbeddings,
				userStats.PendingOpenAI, userStats.PendingGemini)
		}

		// Process user-specific transcriptions
		err = processor.ProcessUserTranscriptions(ctx, flagUser, providerNames, flagBatchSize)
		if err != nil {
			log.Fatalf("❌ Error generating user-specific embeddings: %v", err)
		}

		fmt.Printf("✅ Successfully generated embeddings for user: %s\n", flagUser)
	} else if flagID > 0 {
		fmt.Printf("Generating embeddings for transcription ID: %d\n", flagID)
		err = processSingleTranscription(ctx, embedOrchestrator, storage, flagID, flagProvider, flagForce)
	} else {
		cmd.Help()
		return
	}

	if err != nil {
		log.Fatalf("Error generating embeddings: %v", err)
	}

	fmt.Println("Embedding generation completed successfully!")
}

