// interpretCrossSimilarity provides interpretation for cross-provider similarity
func interpretCrossSimilarity(similarity float64) string {
	switch {
	case similarity >= 0.8:
		return "High correlation - providers agree strongly"
	case similarity >= 0.6:
		return "Good correlation - providers generally agree"
	case similarity >= 0.4:
		return "Moderate correlation - some agreement"
	case similarity >= 0.2:
		return "Low correlation - providers differ significantly"
	default:
		return "Very low correlation - providers disagree substantially"
	}
}
