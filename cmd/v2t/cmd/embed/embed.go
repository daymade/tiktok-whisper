// DuplicatePair represents a pair of similar transcriptions
type DuplicatePair struct {
	ID1        int
	ID2        int
	Text1      string
	Text2      string
	User1      string
	User2      string
	Similarity float64
}

// findDuplicatePairs finds pairs of transcriptions with high similarity
func findDuplicatePairs(db *sql.DB, ctx context.Context, provider string, threshold float64, limit int, user string) ([]DuplicatePair, error) {
	// Choose embedding column based on provider
	var embeddingColumn string
	switch provider {
	case "openai":
		embeddingColumn = "embedding_openai"
	case "gemini":
		embeddingColumn = "embedding_gemini"
	default:
		return nil, fmt.Errorf("unsupported provider: %s", provider)
	}

	// Build query for finding similar pairs
	var query string
	var args []interface{}

	if user != "" {
		// User-specific search
		query = fmt.Sprintf(`
			SELECT 
				t1.id, t2.id,
				t1.transcription, t2.transcription,
				t1.user_nickname, t2.user_nickname,
				1 - (t1.%s <=> t2.%s) as similarity
			FROM transcriptions t1
			CROSS JOIN transcriptions t2
			WHERE t1.id < t2.id
				AND t1.%s IS NOT NULL 
				AND t2.%s IS NOT NULL
				AND (t1.user_nickname = $1 OR t2.user_nickname = $1)
				AND 1 - (t1.%s <=> t2.%s) >= $2
			ORDER BY similarity DESC
			LIMIT $3
		`, embeddingColumn, embeddingColumn, embeddingColumn, embeddingColumn, embeddingColumn, embeddingColumn)
		args = []interface{}{user, threshold, limit}
	} else {
		// Global search
		query = fmt.Sprintf(`
			SELECT 
				t1.id, t2.id,
				t1.transcription, t2.transcription,
				t1.user_nickname, t2.user_nickname,
				1 - (t1.%s <=> t2.%s) as similarity
			FROM transcriptions t1
			CROSS JOIN transcriptions t2
			WHERE t1.id < t2.id
				AND t1.%s IS NOT NULL 
				AND t2.%s IS NOT NULL
				AND 1 - (t1.%s <=> t2.%s) >= $1
			ORDER BY similarity DESC
			LIMIT $2
		`, embeddingColumn, embeddingColumn, embeddingColumn, embeddingColumn, embeddingColumn, embeddingColumn)
		args = []interface{}{threshold, limit}
	}

	rows, err := db.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, fmt.Errorf("failed to execute duplicate search query: %w", err)
	}
	defer rows.Close()

	var pairs []DuplicatePair
	for rows.Next() {
		var pair DuplicatePair
		err := rows.Scan(
			&pair.ID1, &pair.ID2,
			&pair.Text1, &pair.Text2,
			&pair.User1, &pair.User2,
			&pair.Similarity,
		)
		if err != nil {
			return nil, fmt.Errorf("failed to scan duplicate pair: %w", err)
		}
		pairs = append(pairs, pair)
	}

	if err = rows.Err(); err != nil {
		return nil, fmt.Errorf("error iterating duplicate pairs: %w", err)
	}

	return pairs, nil
}

