// processSingleTranscription processes embedding generation for a single transcription by ID
func processSingleTranscription(ctx context.Context, embedOrchestrator *orchestrator.EmbeddingOrchestrator, storage *vector.PgVectorStorage, id int, provider string, force bool) error {
	// Since we need to query the database, let's create a direct connection
	// This is a simplified approach for single record processing
	db, err := pg.GetConnection()
	if err != nil {
		return fmt.Errorf("failed to connect to database: %w", err)
	}
	defer db.Close()

	// Query the transcription by ID
	query := `SELECT id, transcription, user_nickname FROM transcriptions WHERE id = $1`
	row := db.QueryRowContext(ctx, query, id)

	var transcriptionID int
	var text, userNickname string

	err = row.Scan(&transcriptionID, &text, &userNickname)
	if err != nil {
		if err == sql.ErrNoRows {
			return fmt.Errorf("transcription with ID %d not found", id)
		}
		return fmt.Errorf("error querying transcription: %w", err)
	}

	fmt.Printf("Found transcription ID %d (user: %s)\n", transcriptionID, userNickname)
	fmt.Printf("Text preview: %.100s...\n", text)

	// Check if embeddings already exist (unless force is specified)
	if !force {
		needsGeneration := false

		if provider == "openai" || provider == "both" {
			_, err := storage.GetEmbedding(ctx, transcriptionID, "openai")
			if err != nil {
				needsGeneration = true
				fmt.Println("  → OpenAI embedding missing, will generate")
			} else {
				fmt.Println("  ✓ OpenAI embedding already exists, skipping")
			}
		}

		if provider == "gemini" || provider == "both" {
			_, err := storage.GetEmbedding(ctx, transcriptionID, "gemini")
			if err != nil {
				needsGeneration = true
				fmt.Println("  → Gemini embedding missing, will generate")
			} else {
				fmt.Println("  ✓ Gemini embedding already exists, skipping")
			}
		}

		if !needsGeneration {
			fmt.Printf("✅ All required embeddings already exist for transcription ID %d (use --force to regenerate)\n", transcriptionID)
			return nil
		}
	} else {
		fmt.Println("  🔄 Force mode enabled, will regenerate all embeddings")
	}

	// Use the orchestrator to process this single transcription
	err = embedOrchestrator.ProcessTranscription(ctx, transcriptionID, text)
	if err != nil {
		return fmt.Errorf("error processing transcription: %w", err)
	}

	fmt.Printf("✅ Successfully generated and stored embeddings for transcription ID %d\n", transcriptionID)
	return nil
}

